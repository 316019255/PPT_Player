-- ppt-player 的 Postgres 结构（Supabase）。
-- 空库重来：不迁移 SQLite data/ppt-player.db 里的任何数据。
-- 用 npm run db:push 应用；本文件幂等，可以重复执行。
--
-- 关于权限：应用连的是 postgres（表主）角色，Postgres 里表主默认绕过 RLS，
-- 所以数据隔离完全靠每条 SQL 里的 user_id 条件（现有路由都是这么写的）。
-- 不要在这里加 RLS 策略：应用不会设置 auth.uid()，加了只会让所有查询返回空。

CREATE TABLE IF NOT EXISTS users (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          TEXT UNIQUE NOT NULL,
  password_hash  TEXT NOT NULL,
  name           TEXT NOT NULL,
  pro            SMALLINT NOT NULL DEFAULT 0,
  pro_expires_at TIMESTAMPTZ,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS categories (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS presentations (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  title       TEXT NOT NULL DEFAULT '未命名演示文稿',
  data        TEXT NOT NULL DEFAULT '[]',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_presentations_user ON presentations(user_id);
CREATE INDEX IF NOT EXISTS idx_presentations_cat ON presentations(category_id);
CREATE INDEX IF NOT EXISTS idx_categories_user ON categories(user_id);

-- 后台管理的在线素材库（图片/视频），所有用户共享
CREATE TABLE IF NOT EXISTS materials (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind        TEXT NOT NULL CHECK (kind IN ('image', 'video')),
  url         TEXT NOT NULL,
  thumb_url   TEXT,
  category    TEXT NOT NULL DEFAULT '未分类',
  tags        TEXT,
  alt         TEXT,
  title       TEXT NOT NULL DEFAULT '',
  sort        INTEGER NOT NULL DEFAULT 0,
  enabled     SMALLINT NOT NULL DEFAULT 1,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 线上库早建好了 materials，上面那条 CREATE 不会补列，所以三段 ALTER 单独走一遍。
-- 全部 IF NOT EXISTS：这个文件要能对着生产库重复执行。
ALTER TABLE materials ADD COLUMN IF NOT EXISTS title   TEXT    NOT NULL DEFAULT '';
ALTER TABLE materials ADD COLUMN IF NOT EXISTS sort    INTEGER NOT NULL DEFAULT 0;
ALTER TABLE materials ADD COLUMN IF NOT EXISTS enabled SMALLINT NOT NULL DEFAULT 1;

-- url 唯一：后台录入/上传同一条素材时 ON CONFLICT DO NOTHING 去重。
-- Postgres 没有 ADD CONSTRAINT IF NOT EXISTS，唯一性用唯一索引表达，效果一样。
CREATE UNIQUE INDEX IF NOT EXISTS materials_url_key ON materials(url);

CREATE INDEX IF NOT EXISTS idx_materials_kind ON materials(kind);
CREATE INDEX IF NOT EXISTS idx_materials_category ON materials(category);

-- 列表页只要「这叠有几页」，不该把整份 deck 的 JSON 拖回应用再数
-- （29 页的歌稿是 160KB，实测这条链路把它取回来要 3–10 秒）。
-- 包一层 EXCEPTION 而不是裸写 data::jsonb：data 是普通 TEXT 列，历史里只要有一行
-- 不是合法 JSON，整条列表查询就会 500 —— 宁可那一行显示 0 页。
CREATE OR REPLACE FUNCTION slide_count(raw TEXT) RETURNS INTEGER
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  IF raw IS NULL OR jsonb_typeof(raw::jsonb) <> 'array' THEN
    RETURN 0;
  END IF;
  RETURN jsonb_array_length(raw::jsonb);
EXCEPTION WHEN OTHERS THEN
  RETURN 0;
END;
$$;
